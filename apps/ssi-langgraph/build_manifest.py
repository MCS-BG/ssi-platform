def pins() -> list[str]:
    lines = (HERE / "requirements.txt").read_text().splitlines()
    return [ln.strip() for ln in lines if ln.strip() and not ln.lstrip().startswith("#")]


def block(path: pathlib.Path) -> str:
    text = path.read_text()
    return "".join(("    " + line) if line.strip("\n") else "\n" for line in text.splitlines(keepends=True))


def pip_cmd() -> str:
    args = ["python", "-m", "pip", "install", "--no-cache-dir", "--disable-pip-version-check",
            "--only-binary=:all:", "--no-deps", "--quiet", "--target", "/deps", *pins()]
    lines = ",\n".join(f'            "{a}"' for a in args)
    return f"[\n{lines}\n          ]"


