def render() -> str:
    parts = [HEADER, "apiVersion: v1\nkind: ConfigMap\nmetadata:\n  name: ssi-langgraph-code\n  namespace: si-lab\n"
             "  labels:\n    app: ssi-langgraph\ndata:\n"]
    for key, path in FILES.items():
        parts.append(f"  {key}: |\n{block(path)}")
    parts.append(DEPLOYMENT.format(image=PY_IMAGE, pip=pip_cmd()))
    return "".join(parts)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text() != text:
            print(f"{OUT.relative_to(REPO)} is out of date: run python3 apps/ssi-langgraph/build_manifest.py")
            return 1
        print(f"{OUT.relative_to(REPO)} is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
